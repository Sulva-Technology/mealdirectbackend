import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import { IsIn, IsOptional, Matches, MaxLength } from 'class-validator';

import { IsDatabaseUuid } from '../../../common/validation.js';
import { funnelEventNames } from '../analytics.types.js';
import type { FunnelEventName } from '../analytics.types.js';

const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function normalizeSlug(value: unknown): unknown {
  return typeof value === 'string' ? value.trim().toLowerCase() : value;
}

export class RecordFunnelEventDto {
  @ApiProperty({ enum: funnelEventNames, type: String })
  @IsIn(funnelEventNames)
  event!: FunnelEventName;

  @ApiProperty({
    description: 'Random per-device id generated by the app; groups pre-signup steps.',
    format: 'uuid',
    type: String
  })
  @IsDatabaseUuid()
  anonymousId!: string;

  @ApiPropertyOptional({ format: 'uuid', type: String })
  @IsOptional()
  @IsDatabaseUuid()
  campusId?: string;

  @ApiPropertyOptional({
    description:
      'Campus slug from a ?campus=<slug> link. Unknown slugs are recorded without a campus.',
    example: 'venite-university',
    maxLength: 80,
    pattern: slugPattern.source,
    type: String
  })
  @IsOptional()
  @Transform(({ value }) => normalizeSlug(value))
  @MaxLength(80)
  @Matches(slugPattern, { message: 'campusSlug must be a campus slug.' })
  campusSlug?: string;
}

export class SignupFunnelQueryDto {
  @ApiPropertyOptional({ format: 'uuid', type: String })
  @IsOptional()
  @IsDatabaseUuid()
  campusId?: string;

  @ApiPropertyOptional({ pattern: '^\\d{4}-\\d{2}-\\d{2}$', type: String })
  @IsOptional()
  @Matches(/^\d{4}-\d{2}-\d{2}$/)
  dateFrom?: string;

  @ApiPropertyOptional({ pattern: '^\\d{4}-\\d{2}-\\d{2}$', type: String })
  @IsOptional()
  @Matches(/^\d{4}-\d{2}-\d{2}$/)
  dateTo?: string;
}
