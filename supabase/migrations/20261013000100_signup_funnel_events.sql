begin;

-- Signup funnel tracking. The customer app reports the client-only steps of the signup
-- funnel (campus link opened, signup started/completed, campus and delivery point picked);
-- the later steps (onboarding completed, first paid order) are read from profiles and
-- orders, so they never depend on a client event arriving. Read through
-- GET /admin/analytics/funnel.
create table public.funnel_events (
  id uuid primary key default gen_random_uuid(),
  event text not null,
  anonymous_id uuid not null,
  user_id uuid references public.profiles(id) on delete set null,
  campus_id uuid references public.campuses(id) on delete set null,
  occurred_at timestamptz not null default now(),
  constraint funnel_events_event_valid check (
    event in (
      'campus_link_opened',
      'signup_started',
      'signup_completed',
      'campus_selected',
      'location_selected'
    )
  )
);

comment on table public.funnel_events is 'Client-reported signup funnel steps from the customer app. Written by POST /analytics/events, read by GET /admin/analytics/funnel. RLS deny-all: only the privileged application role touches it.';
comment on column public.funnel_events.anonymous_id is 'Random per-device id generated by the customer app, so pre-signup steps can be counted as distinct people.';
comment on column public.funnel_events.user_id is 'Set only from a verified bearer token on the request; never taken from the request body.';
comment on column public.funnel_events.campus_id is 'Campus the step relates to: the campus picked, or the campus whose link (?campus=<slug>) brought the visitor in.';
comment on column public.funnel_events.occurred_at is 'Server receive time; client clocks are not trusted.';

create index funnel_events_event_occurred_idx on public.funnel_events (event, occurred_at);
create index funnel_events_campus_occurred_idx on public.funnel_events (campus_id, occurred_at)
  where campus_id is not null;

alter table public.funnel_events enable row level security;

revoke all on public.funnel_events from anon, authenticated;

commit;
